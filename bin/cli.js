function readVersion() {
  try {
    const pkg = JSON.parse(fs.readFileSync(path.join(PACKAGE_ROOT, 'package.json'), 'utf8'));
    return typeof pkg.version === 'string' ? pkg.version : FALLBACK_VERSION;
  } catch {
    return FALLBACK_VERSION;
  }
}

function sha256(content) {
  return crypto.createHash('sha256').update(content).digest('hex');
}

function isDirectory(target) {
  try {
    return fs.statSync(target).isDirectory();
  } catch {
    return false;
  }
}

function addCheck(checks, area, id, level, message) {
  checks.push({ area, id, level, message });
}

function inspectPack(root, area) {
  const checks = [];
  const label = area === 'behavior-pack' ? 'Behavior Pack' : 'Resource Pack';

  if (!fs.existsSync(root)) {
    addCheck(checks, area, 'root.exists', 'error', `${label} のパスが存在しません: ${root}`);
    return checks;
  }
  if (!isDirectory(root)) {
    addCheck(checks, area, 'root.directory', 'error', `${label} のパスがディレクトリではありません: ${root}`);
    return checks;
  }
  addCheck(checks, area, 'root.directory', 'ok', `${label} のディレクトリを確認しました`);

  const manifestPath = path.join(root, 'manifest.json');
  if (!fs.existsSync(manifestPath)) {
    addCheck(checks, area, 'manifest.exists', 'error', 'manifest.json がありません');
    return checks;
  }

  let manifest;
  try {
    manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  } catch (error) {
    addCheck(checks, area, 'manifest.json', 'error', `manifest.json を JSON として読めません: ${error.message}`);
    return checks;
  }
  addCheck(checks, area, 'manifest.exists', 'ok', 'manifest.json を読み込みました');

  // JSON としては読めてもルートがオブジェクトでない manifest は無効。
  // null のままプロパティを読むと TypeError で CLI が落ちるため、ここで止める。
  if (!manifest || typeof manifest !== 'object' || Array.isArray(manifest)) {
    addCheck(
      checks,
      area,
      'manifest.root',
      'error',
      'manifest.json のルートがオブジェクトではありません。manifest の形式を確認してください',
    );
    return checks;
  }

  const header = manifest.header;
  if (!header || typeof header !== 'object') {
    addCheck(checks, area, 'manifest.header', 'error', 'manifest.header がありません');
  } else {
    // min_engine_version は配列（format_version 2 まで）と SemVer 文字列（format_version 3 では必須）の
    // どちらも有効。配列だけを有効扱いすると、正しい v3 manifest に「配列でありません」と誤案内し、
    // 利用者が文字列を配列へ書き換えて逆に壊しかねない。
    const minEngineVersion = header.min_engine_version;
    let minEngineText = null;
    if (Array.isArray(minEngineVersion)) {
      minEngineText = minEngineVersion.join('.');
    } else if (typeof minEngineVersion === 'string' && minEngineVersion.trim() !== '') {
      minEngineText = minEngineVersion.trim();
    }
    if (minEngineText !== null) {
      addCheck(
        checks,
        area,
        'manifest.min_engine_version',
        'ok',
        `min_engine_version: ${minEngineText}（対応ゲーム版は実機で記録する）`,
      );
    } else if (minEngineVersion === undefined) {
      addCheck(checks, area, 'manifest.min_engine_version', 'warn', 'header.min_engine_version がありません');
    } else {
      addCheck(
        checks,
        area,
        'manifest.min_engine_version',
        'warn',
        'header.min_engine_version が配列（例: [1, 21, 0]）でも SemVer 文字列（例: "1.26.40"）でもありません',
      );
    }
  }

  if (area === 'behavior-pack') {
    const modules = Array.isArray(manifest.modules) ? manifest.modules : [];
    const scriptModule = modules.find((module) => module && module.type === 'script');
    if (!scriptModule) {
      addCheck(checks, area, 'bp.script-module', 'warn', 'script モジュールが manifest.modules にありません');
    } else {
      addCheck(checks, area, 'bp.script-module', 'ok', 'script モジュールがあります');
      if (typeof scriptModule.entry === 'string') {
        const entryPath = path.join(root, scriptModule.entry);
        if (fs.existsSync(entryPath)) {
          addCheck(checks, area, 'bp.entry', 'ok', `script entry が存在します: ${scriptModule.entry}`);
        } else {
          addCheck(
            checks,
            area,
            'bp.entry',
            'warn',
            `script entry が見つかりません（ビルド前なら想定内）: ${scriptModule.entry}`,
          );
        }
      } else {
        addCheck(checks, area, 'bp.entry', 'warn', 'script モジュールの entry が文字列ではありません');
      }
    }

    const dependencies = Array.isArray(manifest.dependencies) ? manifest.dependencies : [];
    const hasServer = dependencies.some(
      (dependency) => dependency && dependency.module_name === '@minecraft/server',
    );
    if (hasServer) {
      addCheck(checks, area, 'bp.dependency', 'ok', '@minecraft/server への dependency があります');
    } else {
      addCheck(
        checks,
        area,
        'bp.dependency',
        'warn',
        '@minecraft/server への dependency がありません。Experimental モジュールの指定を確認してください',
      );
    }

    addCheck(
      checks,
      area,
      'bp.experimental',
      'info',
      'Experimental API の有効化と @minecraft/server の版は manifest だけでは確定できません。ゲーム内で確認し、記録してください',
    );
  } else {
    // Resource Pack として読み込まれるには type: "resources" のモジュールが必須。
    // これがないパックへファイルを追加しても Minecraft は読み込まないため、導入前にエラーにする。
    const modules = Array.isArray(manifest.modules) ? manifest.modules : [];
    const resourcesModule = modules.find((module) => module && module.type === 'resources');
    if (resourcesModule) {
      addCheck(checks, area, 'rp.resources-module', 'ok', 'resources モジュールがあります');
    } else {
      addCheck(
        checks,
        area,
        'rp.resources-module',
        'error',
        Array.isArray(manifest.modules)
          ? 'manifest.modules に type: "resources" のモジュールがありません。この状態では Resource Pack として読み込まれないため、導入しても有効になりません'
          : 'manifest.modules が配列でありません。Resource Pack には type: "resources" のモジュールが必要です',
      );
    }

    const uiDir = path.join(root, 'ui');
    if (isDirectory(uiDir)) {
      addCheck(checks, area, 'rp.ui', 'ok', 'ui/ ディレクトリがあります');
    } else {
      addCheck(checks, area, 'rp.ui', 'warn', 'ui/ ディレクトリがありません');
    }

    const chestScreen = path.join(uiDir, 'chest_screen.json');
    if (fs.existsSync(chestScreen)) {
      addCheck(
        checks,
        area,
        'rp.chest-screen',
        'warn',
        '既存の ui/chest_screen.json を検出しました。この CLI は変更しません。手動マージとバックアップが必要です',
      );
    }

    for (const [index, file] of TEMPLATE_FILES.entries()) {
      if (fs.existsSync(path.join(root, file.relativePath))) {
        addCheck(
          checks,
          area,
          `rp.template-file-${index}`,
          'warn',
          `${file.relativePath} が既にあります。${INSTALL_FLAG} 指定時は上書きせず、内容が同梱テンプレートと異なる場合は競合として中断します`,
        );
      }
    }

    if (fs.existsSync(path.join(uiDir, '_ui_defs.json'))) {
      addCheck(
        checks,
        area,
        'rp.ui-defs',
        'info',
        'ui/_ui_defs.json があります。既定では既存の _ui_defs.json を自動変更しません。' +
          `${REGISTER_UI_DEFS_FLAG} を明示した場合だけ不足分をバックアップ付きで追記します。` +
          '手動登録も可能で、generate-resource-pack の生成物は登録済みです',
      );
    }

    addCheck(
      checks,
      area,
      'rp.json-ui-unverified',
      'warn',
      `JSON UI と画面への適用方法は実機未検証です。ui/invui.json と試験的接続 2 ファイルは置いただけでは有効にならず、` +
        `既存 Resource Pack では ui/_ui_defs.json への登録が必要です（既定は手動、${REGISTER_UI_DEFS_FLAG} 明示時は追記）。` +
        `導入は ${INSTALL_FLAG} 指定時のみ行います`,
    );
  }

  return checks;
}

function formatDiff(relativePath, templateText, existingText) {
  const lines = [`--- template: ${relativePath}`, `+++ existing: ${relativePath}`];
  const limit = 40;
  const templateLines = templateText.replace(/\r\n/g, '\n').split('\n');
  const existingLines = existingText.replace(/\r\n/g, '\n').split('\n');

  for (const line of templateLines.slice(0, limit)) {
    lines.push(`-${line}`);
  }
  if (templateLines.length > limit) {
    lines.push(`-... (${templateLines.length - limit} 行を省略)`);
  }
  for (const line of existingLines.slice(0, limit)) {
    lines.push(`+${line}`);
  }
  if (existingLines.length > limit) {
    lines.push(`+... (${existingLines.length - limit} 行を省略)`);
  }

  return lines.join('\n');
}

function existingAncestor(target) {
  let current = target;
  while (!fs.existsSync(current)) {
    const parent = path.dirname(current);
    if (parent === current) {
      return null;
    }
    current = parent;
  }
  return { path: current, stat: fs.statSync(current) };
}

// root より下の経路にシンボリックリンクがあればそのパスを返す。
// パック外（例: ui/ が外部ディレクトリを指す）へ書き込まないための検査。
function findSymlinkComponent(root, target) {
  const relative = path.relative(root, target);
  if (relative === '' || relative.startsWith(`..${path.sep}`) || relative === '..' || path.isAbsolute(relative)) {
    return null;
  }
  let current = root;
  for (const part of relative.split(path.sep)) {
    current = path.join(current, part);
    let stat;
    try {
      stat = fs.lstatSync(current);
    } catch (error) {
      if (error.code === 'ENOENT') {
        return null;
      }
      throw error;
    }
    if (stat.isSymbolicLink()) {
      return current;
    }
  }
  return null;
}

function sameFileIdentity(stat, identity) {
  return (
    Boolean(identity) &&
    Boolean(stat) &&
    stat.isFile() &&
    stat.dev === identity.dev &&
    stat.ino === identity.ino
  );
}

// 自分が排他的に作り、dev/ino で同一と確認できたファイルだけを削除する。
// 別プロセスが置き換えたファイルは決して消さない。
// dev/ino が同じでも、別プロセスが in-place で内容を書き直していることがある。
// 期待する内容（expectedContent）を渡された場合は現物と比較し、異なるなら残して報告する。
// ponytail: 確認と unlink の間の TOCTOU は塞ぎ切らない。塞ぐなら fd + flock が要る。
function removeDestinationIfOwned(destination, identity, expectedContent = null) {
  let stat;
  try {
    stat = fs.lstatSync(destination);
  } catch (error) {
    if (error.code === 'ENOENT') {
      return { removed: true, reason: null };
    }
    return { removed: false, reason: error.message };
  }
  if (!sameFileIdentity(stat, identity)) {
    return { removed: false, reason: '自分が作成したファイルと確認できないため削除しません' };
  }
  if (expectedContent) {
    let currentContent;
    try {
      currentContent = fs.readFileSync(destination);
    } catch (error) {
      if (error.code === 'ENOENT') {
        return { removed: true, reason: null };
      }
      return { removed: false, reason: `内容を確認できないため削除しません: ${error.message}` };
    }
    if (!currentContent.equals(expectedContent)) {
      return {
        removed: false,
        reason: '配置後に別プロセスが内容を変更しているため削除しません（元の内容と異なります）',
      };
    }
  }
  try {
    fs.unlinkSync(destination);
    return { removed: true, reason: null };
  } catch (error) {
    if (error.code === 'ENOENT') {
      return { removed: true, reason: null };
    }
    return { removed: false, reason: error.message };
  }
}

function preflightTemplate(resourcePack) {
  const entries = [];
  const conflicts = [];

  for (const file of TEMPLATE_FILES) {
    let templateContent;
    try {
      templateContent = fs.readFileSync(file.source);
    } catch (error) {
      return {
        error: `同梱テンプレートを読めません: ${file.source} (${error.message})`,
        entries: [],
        conflicts: [],
      };
    }

    const destination = path.join(resourcePack, file.relativePath);
    const digest = sha256(templateContent);

    let linkedPath;
    try {
      linkedPath = findSymlinkComponent(resourcePack, destination);
    } catch (error) {
      return {
        error: `導入先の経路を確認できません: ${destination} (${error.message})`,
        entries: [],
        conflicts: [],
      };
    }
    if (linkedPath) {
      conflicts.push({
        path: file.relativePath,
        reason: `導入先の経路にシンボリックリンクがあります。パック外へ書き込まないため導入しません: ${linkedPath}`,
        diff: null,
      });
      continue;
    }

    let stat;
    try {
      stat = fs.lstatSync(destination);
    } catch (error) {
      if (error.code !== 'ENOENT') {
        return {
          error: `導入先を確認できません: ${destination} (${error.message})`,
          entries: [],
          conflicts: [],
        };
      }
    }

    if (stat) {
      if (!stat.isFile() || stat.isSymbolicLink()) {
        conflicts.push({
          path: file.relativePath,
          reason: '導入先にファイル以外（ディレクトリまたはシンボリックリンク）があります。上書きしません。',
          diff: null,
        });
      } else {
        const existingContent = fs.readFileSync(destination);
        if (existingContent.equals(templateContent)) {
          entries.push({
            relativePath: file.relativePath,
            destination,
            templateContent,
            digest,
            action: 'already-present',
          });
        } else {
          conflicts.push({
            path: file.relativePath,
            reason: '既存ファイルの内容が同梱テンプレートと異なります。上書きしません。',
            diff: formatDiff(
              file.relativePath,
              templateContent.toString('utf8'),
              existingContent.toString('utf8'),
            ),
          });
        }
      }
      continue;
    }

    const parent = existingAncestor(path.dirname(destination));
    if (!parent) {
      return {
        error: `導入先の親ディレクトリを解決できません: ${destination}`,
        entries: [],
        conflicts: [],
      };
    }
    if (!parent.stat.isDirectory()) {
      return {
        error: `導入先の親がディレクトリではありません: ${parent.path}`,
        entries: [],
        conflicts: [],
      };
    }

    entries.push({
      relativePath: file.relativePath,
      destination,
      templateContent,
      digest,
      action: 'create',
    });
  }

  return { error: null, entries, conflicts };
}

// 既存 _ui_defs.json は変更しない。登録状況だけを読み取り、手動作業を案内する。
// verified は「ui_defs 文字列配列として読めた」こと。false は未登録ではなく登録未確認を表す。
function inspectUiDefs(resourcePack) {
  const result = {
    path: UI_DEFS_RELATIVE_PATH,
    action: 'not-modified',
    exists: false,
    verified: false,
    registered: [],
    missing: [...TEMPLATE_PATHS],
    error: null,
  };

  let text;
  try {
    text = fs.readFileSync(path.join(resourcePack, UI_DEFS_RELATIVE_PATH), 'utf8');
  } catch (error) {
    if (error.code !== 'ENOENT') {
      result.error = error.message;
    }
    return result;
  }
  result.exists = true;

  let parsed;
  try {
    parsed = JSON.parse(text);
  } catch (error) {
    result.error = error.message;
    return result;
  }
  const defs = Array.isArray(parsed && parsed.ui_defs) ? parsed.ui_defs : null;
  if (defs === null || defs.some((entry) => typeof entry !== 'string')) {
    // JSON ではあるが ui_defs 文字列配列がない。未登録ではなく登録未確認として扱う。
    return result;
  }
  result.verified = true;
  result.registered = TEMPLATE_PATHS.filter((entry) => defs.includes(entry));
  result.missing = TEMPLATE_PATHS.filter((entry) => !defs.includes(entry));
  return result;
}

function uiDefsConflict(reason) {
  return { path: UI_DEFS_RELATIVE_PATH, reason, diff: null };
}

// --register-ui-defs 用の事前検査。書き込みはせず、競合・解析不能・追記内容だけを決める。
function preflightUiDefsRegistration(resourcePack) {
  const destination = path.join(resourcePack, UI_DEFS_RELATIVE_PATH);
  const result = {
    resourcePack,
    destination,
    status: 'failed',
    exists: false,
    verified: false,
    registered: [],
    missing: [...TEMPLATE_PATHS],
    added: [],
    originalContent: null,
    nextContent: null,
    backup: null,
    error: null,
    conflicts: [],
  };

  let linkedPath;
  try {
    linkedPath = findSymlinkComponent(resourcePack, destination);
  } catch (error) {
    result.error = `ui/_ui_defs.json の経路を確認できません: ${error.message}`;
    return result;
  }
  if (linkedPath) {
    result.status = 'conflict';
    result.conflicts = [
      uiDefsConflict(`導入先の経路にシンボリックリンクがあります。パック外へ書き込まないため変更しません: ${linkedPath}`),
    ];
    return result;
  }

  let stat;
  try {
    stat = fs.lstatSync(destination);
  } catch (error) {
    if (error.code === 'ENOENT') {
      result.error =
        'ui/_ui_defs.json がありません。--register-ui-defs は既存ファイルへの追記だけを行うため、' +
        '先に作成するか generate-resource-pack を使ってください。';
      return result;
    }
    result.error = `ui/_ui_defs.json を確認できません: ${error.message}`;
    return result;
  }
  result.exists = true;
  if (!stat.isFile() || stat.isSymbolicLink()) {
    result.status = 'conflict';
    result.conflicts = [uiDefsConflict('ui/_ui_defs.json が通常ファイルではありません。変更しません。')];
    return result;
  }

  let originalContent;
  try {
    originalContent = fs.readFileSync(destination);
  } catch (error) {
    result.error = `ui/_ui_defs.json を読めません: ${error.message}`;
    return result;
  }
  const text = originalContent.toString('utf8');

  let parsed;
  try {
    parsed = JSON.parse(text);
  } catch (error) {
    result.status = 'conflict';
    result.conflicts = [uiDefsConflict(`ui/_ui_defs.json を JSON として読めないため変更しません: ${error.message}`)];
    return result;
  }
  if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) {
    result.status = 'conflict';
    result.conflicts = [uiDefsConflict('ui/_ui_defs.json のルートがオブジェクトではないため変更しません。')];
    return result;
  }
  if (!Array.isArray(parsed.ui_defs)) {
    result.status = 'conflict';
    result.conflicts = [uiDefsConflict('ui/_ui_defs.json に ui_defs 配列がないため変更しません。')];
    return result;
  }
  if (parsed.ui_defs.some((entry) => typeof entry !== 'string')) {
    result.status = 'conflict';
    result.conflicts = [uiDefsConflict('ui_defs 配列に文字列以外の要素があるため変更しません。')];
    return result;
  }

  result.verified = true;
  result.registered = TEMPLATE_PATHS.filter((entry) => parsed.ui_defs.includes(entry));
  result.missing = TEMPLATE_PATHS.filter((entry) => !parsed.ui_defs.includes(entry));
  if (result.missing.length === 0) {
    result.status = 'already-registered';
    return result;
  }

  // 既存の並び・キー順・インデント・改行コードは保ち、追記した分だけを差分にする。
  const newline = text.includes('\r\n') ? '\r\n' : '\n';
  const indentMatch = text.match(/\n([ \t]+)"/);
  const indent = text.includes('\n') ? (indentMatch ? indentMatch[1] : 2) : 0;
  const next = { ...parsed, ui_defs: [...parsed.ui_defs, ...result.missing] };
  let nextText = JSON.stringify(next, null, indent);
  if (/\r?\n$/.test(text)) {
    nextText += '\n';
  }
  nextText = nextText.replace(/\n/g, newline);
  result.originalContent = originalContent;
  result.nextContent = Buffer.from(nextText, 'utf8');
  result.added = [...result.missing];
  result.status = 'pending';
  return result;
}

// 事前検査から書き込みまでの間に経路がシンボリックリンクへ差し替えられていないか確認する。
// テンプレート配置と同じく、書き込み直前にもう一度見る。
function assertUiDefsPath(resourcePack, destination) {
  const linkedPath = findSymlinkComponent(resourcePack, destination);
  if (linkedPath) {
    throw new Error(`ui/_ui_defs.json の経路がシンボリックリンクに変わったため書き込みませんでした: ${linkedPath}`);
  }
}

// 追記した自分のファイル（dev/ino が一致）だけを、シンボリックリンクを辿らずに戻す。
// バックアップは消さない。呼び出し側が復元結果を検証してから片付ける。
// 書き戻す直前にも、開いた fd から内容が追記したままか確認する。landed の判定から
// ここまでに別プロセスが in-place で書き換えていた場合、inode は変わらないため
// dev/ino だけでは検出できず、truncate するとその変更を消してしまう。
function restoreUiDefsFromBackup(destination, identity, backupPath, appendedContent) {
  const flags = fs.constants.O_RDWR | (fs.constants.O_NOFOLLOW || 0);
  let fd;
  try {
    fd = fs.openSync(destination, flags);
  } catch (error) {
    if (error.code === 'ELOOP') {
      throw new Error('復元先の経路がシンボリックリンクに変わったため書き戻しません');
    }
    throw error;
  }
  try {
    const openedStat = fs.fstatSync(fd);
    if (!sameFileIdentity(openedStat, identity)) {
      throw new Error('復元先が追記したファイルと確認できないため書き戻しません');
    }
    // 位置 0 から読む。fd の位置を進めないよう readSync に明示的な位置を渡す。
    const currentContent = Buffer.alloc(openedStat.size);
    let read = 0;
    while (read < openedStat.size) {
      const bytes = fs.readSync(fd, currentContent, read, openedStat.size - read, read);
      if (bytes === 0) {
        break;
      }
      read += bytes;
    }
    if (read !== openedStat.size || !currentContent.equals(appendedContent)) {
      throw new Error('追記後に別プロセスが内容を変更したため書き戻しません');
    }
    const backupContent = fs.readFileSync(backupPath);
    fs.ftruncateSync(fd, 0);
    // fd の位置に依存せず先頭から書く。
    let written = 0;
    while (written < backupContent.length) {
      written += fs.writeSync(fd, backupContent, written, backupContent.length - written, written);
    }
    fs.fsyncSync(fd);
  } finally {
    try {
      fs.closeSync(fd);
    } catch {
      // close 失敗は復元結果を変えない。
    }
  }
}

// バックアップを排他的に作り、内容が変わっていないことを確認してから rename で置き換える。
// 失敗時は一時ファイルを片付ける。追記が確定した後の例外は、追記した inode と内容を
// 確認できた場合だけ元へ戻し、確認できなければバックアップを残して報告する。
// ponytail: 内容比較と rename の間の TOCTOU は塞ぎ切らない。塞ぐなら fd + flock が要る。
function registerUiDefs(preflight) {
  const { resourcePack, destination, originalContent, nextContent } = preflight;
  const nonce = `${process.pid}.${crypto.randomBytes(6).toString('hex')}`;
  const backupPath = `${destination}.invui-backup.${nonce}.bak`;
  const tempPath = path.join(
    path.dirname(destination),
    `.${path.basename(destination)}.${nonce}.tmp`,
  );
  let backupCreated = false;
  let tempCreated = false;
  let originalIdentity = null;
  let tempIdentity = null;

  try {
    assertUiDefsPath(resourcePack, destination);
    const originalStat = fs.lstatSync(destination);
    if (!originalStat.isFile() || originalStat.isSymbolicLink()) {
      throw new Error('ui/_ui_defs.json が通常ファイルではないため書き込みませんでした。');
    }
    originalIdentity = { dev: originalStat.dev, ino: originalStat.ino };
    fs.copyFileSync(destination, backupPath, fs.constants.COPYFILE_EXCL);
    backupCreated = true;
    if (!fs.readFileSync(destination).equals(originalContent)) {
      throw new Error('確認中に ui/_ui_defs.json が別プロセスに変更されたため書き込みませんでした。');
    }
    tempIdentity = writeExclusiveTempFile(tempPath, nextContent);
    tempCreated = true;
    if (!fs.readFileSync(destination).equals(originalContent)) {
      throw new Error('確認中に ui/_ui_defs.json が別プロセスに変更されたため書き込みませんでした。');
    }
    // rename は追記を確定させる操作なので、直前に経路をもう一度見る。
    assertUiDefsPath(resourcePack, destination);
    fs.renameSync(tempPath, destination);
    tempCreated = false;
    // rename 後に差し替えられていないこと（inode）を確認してから成功とする。
    if (!sameFileIdentity(fs.lstatSync(destination), tempIdentity)) {
      throw new Error('追記後の ui/_ui_defs.json を自分が置いたファイルと確認できませんでした。');
    }
    return backupPath;
  } catch (error) {
    if (tempCreated) {
      const cleanup = removeDestinationIfOwned(tempPath, tempIdentity);
      if (!cleanup.removed) {
        error.message += ` / 一時ファイルを削除できません: ${tempPath} (${cleanup.reason})`;
      }
    }
    if (backupCreated) {
      let currentStat = null;
      let currentError = null;
      try {
        currentStat = fs.lstatSync(destination);
      } catch (lstatError) {
        currentError = lstatError;
      }
      // rename 後も追記したのと同じ inode で、かつ内容が追記したままの場合だけ戻す。
      // 別ファイル（内容が同じでも）や、追記後に変更されたファイルは上書きしない。
      let landed = false;
      if (sameFileIdentity(currentStat, tempIdentity)) {
        try {
          landed = fs.readFileSync(destination).equals(nextContent);
        } catch {
          landed = false;
        }
      }
      let restoreNote = null;
      if (landed) {
        try {
          assertUiDefsPath(resourcePack, destination);
          restoreUiDefsFromBackup(destination, tempIdentity, backupPath, nextContent);
        } catch (restoreError) {
          restoreNote = `追記を元に戻せませんでした: ${restoreError.message}`;
        }
      } else if (currentError && currentError.code !== 'ENOENT') {
        restoreNote = `追記後の状態を確認できません: ${currentError.message}`;
      } else {
        restoreNote = currentStat
          ? '追記後に別プロセスが内容またはファイルを変更したため自動では戻しません'
          : '追記したファイルが見つからないため自動では戻しません';
      }
      // 復元できた場合も、宛先が自分の追記ファイル（または元のファイル）で、
      // 内容が元に戻っていると確認できた場合だけバックアップを片付ける。
      let afterStat = null;
      let afterContent = null;
      try {
        afterStat = fs.lstatSync(destination);
        afterContent = fs.readFileSync(destination);
      } catch {
        afterContent = null;
      }
      const recovered =
        afterContent !== null &&
        afterContent.equals(originalContent) &&
        (sameFileIdentity(afterStat, tempIdentity) || sameFileIdentity(afterStat, originalIdentity));
      if (recovered) {
        try {
          fs.unlinkSync(backupPath);
        } catch (cleanupError) {
          error.message += ` / バックアップを削除できません: ${backupPath} (${cleanupError.message})`;
        }
      } else {
        error.message +=
          ` / ${restoreNote ? `${restoreNote} / ` : ''}現在の内容は ${backupPath} に退避しています`;
      }
    }
    throw error;
  }
}

function conflictError(destination) {
  const conflict = new Error(`導入先が同時に作成されました: ${destination}`);
  conflict.code = 'EEXIST';
  return conflict;
}

// 'wx' で fd を確保してから書き込む。open できなかった時点で自分はまだ何も
// 作っていない（EEXIST の既存ファイル、EACCES・EMFILE・ENOSPC など）ので、
// そのパスは消さない。書き込みに失敗した場合（ENOSPC など）だけ、確保した fd と
// dev/ino が一致する一時ファイルを消してから例外を投げる。呼び出し側の後片付けは
// 書き込み成功後の一時ファイルを前提にしているため、ここで消さないと残骸になる。
function writeExclusiveTempFile(tempPath, content) {
  let fd = fs.openSync(tempPath, 'wx', 0o644);
  let identity = null;
  try {
    const stat = fs.fstatSync(fd);
    identity = { dev: stat.dev, ino: stat.ino };
    fs.writeFileSync(fd, content);
    return identity;
  } catch (error) {
    try {
      fs.closeSync(fd);
    } catch {
      // 下の finally でも閉じられないので、ここでは失敗を無視する。
    }
    fd = null;
    const cleanup = removeDestinationIfOwned(tempPath, identity);
    if (!cleanup.removed) {
      error.message += ` / 一時ファイルを削除できません: ${tempPath} (${cleanup.reason})`;
    }
    throw error;
  } finally {
    if (fd !== null) {
      try {
        fs.closeSync(fd);
      } catch {
        // close 失敗は一時ファイルの作成結果を変えない。
      }
    }
  }
}

function placeFileWithoutOverwrite(tempPath, destination) {
  try {
    // ハードリンクは宛先が存在すると EEXIST で失敗するため、上書きしない。
    fs.linkSync(tempPath, destination);
    const stat = fs.statSync(tempPath);
    return { dev: stat.dev, ino: stat.ino };
  } catch (error) {
    if (error.code === 'EEXIST') {
      throw conflictError(destination);
    }
    const fallbackCodes = new Set(['EPERM', 'ENOTSUP', 'EOPNOTSUPP', 'EXDEV']);
    if (!fallbackCodes.has(error.code)) {
      throw error;
    }
  }

  // ハードリンクを作れないファイルシステム向け。O_EXCL で排他作成する。
  // open に成功した時点でそのファイルは自分だけが作ったとみなせる。
  const content = fs.readFileSync(tempPath);
  let fd;
  try {
    fd = fs.openSync(destination, 'wx', 0o644);
  } catch (error) {
    if (error.code === 'EEXIST') {
      throw conflictError(destination);
    }
    throw error;
  }
  let identity = null;
  try {
    const stat = fs.fstatSync(fd);
    identity = { dev: stat.dev, ino: stat.ino };
    fs.writeFileSync(fd, content);
    return identity;
  } catch (error) {
    // 部分書き込みを戻すのは、自分の fd の dev/ino が宛先と一致した場合だけ。
    // 失敗経路でも「別プロセスのファイルを消さない」を守る。
    try {
      fs.closeSync(fd);
    } catch {
      // 下の finally でも閉じられないので、ここでは失敗を無視する。
    }
    fd = null;
    const cleanup = removeDestinationIfOwned(destination, identity);
    if (!cleanup.removed) {
      error.message = `${error.message} / 部分書き込みを削除できません: ${destination} (${cleanup.reason})`;
    }
    throw error;
  } finally {
    if (fd !== null) {
      try {
        fs.closeSync(fd);
      } catch {
        // close 失敗は配置結果を変えない。
      }
    }
  }
}

function applyTemplate(resourcePack, options = {}) {
  const registerRequested = options.registerUiDefs === true;
  const templateRoot = path.join(PACKAGE_ROOT, 'resource_pack');
  const preflight = preflightTemplate(resourcePack);
  if (preflight.error) {
    return {
      requested: true,
      status: 'failed',
      error: preflight.error,
      templateRoot,
      files: [],
      conflicts: [],
      createdDirectories: [],
    };
  }

  // 登録の事前検査を先に行い、競合時はテンプレートを 1 ファイルも追加しない。
  const uiDefsPreflight = registerRequested ? preflightUiDefsRegistration(resourcePack) : null;
  if (uiDefsPreflight && uiDefsPreflight.status === 'failed') {
    return {
      requested: true,
      status: 'failed',
      error: `ui/_ui_defs.json の登録前検査で失敗したため導入を中断しました: ${uiDefsPreflight.error}`,
      templateRoot,
      files: [],
      conflicts: [],
      createdDirectories: [],
    };
  }
  if (uiDefsPreflight && uiDefsPreflight.conflicts.length > 0) {
    return {
      requested: true,
      status: 'conflict',
      error: '既存の ui/_ui_defs.json と競合したため導入を中断しました。既存ファイルは変更していません。',
      templateRoot,
      files: [],
      conflicts: uiDefsPreflight.conflicts,
      createdDirectories: [],
    };
  }

  if (preflight.conflicts.length > 0) {
    return {
      requested: true,
      status: 'conflict',
      error: '既存ファイルと競合したため導入を中断しました。既存ファイルは変更していません。',
      templateRoot,
      files: [],
      conflicts: preflight.conflicts,
      createdDirectories: [],
    };
  }

  const uiDefsReport = () => {
    if (!registerRequested) {
      return inspectUiDefs(resourcePack);
    }
    return {
      path: UI_DEFS_RELATIVE_PATH,
      action: uiDefsPreflight.status,
      exists: uiDefsPreflight.exists,
      verified: uiDefsPreflight.verified,
      registered: [...uiDefsPreflight.registered],
      missing: [...uiDefsPreflight.missing],
      added: [...uiDefsPreflight.added],
      backup: uiDefsPreflight.backup,
      error: uiDefsPreflight.error,
    };
  };
  const registerNow = () => {
    if (!uiDefsPreflight || uiDefsPreflight.status !== 'pending') {
      return;
    }
    uiDefsPreflight.backup = registerUiDefs(uiDefsPreflight);
    uiDefsPreflight.status = 'registered';
    uiDefsPreflight.registered = [...TEMPLATE_PATHS];
    uiDefsPreflight.missing = [];
  };
  const uiDefsRestore = () =>
    uiDefsPreflight && uiDefsPreflight.status === 'registered'
      ? [`cp "${uiDefsPreflight.backup}" "${uiDefsPreflight.destination}"`]
      : [];

  const toCreate = preflight.entries.filter((entry) => entry.action === 'create');
  if (toCreate.length === 0) {
    try {
      registerNow();
    } catch (error) {
      return {
        requested: true,
        status: 'failed',
        error: `ui/_ui_defs.json の登録中に失敗したため、既存ファイルは変更していません: ${error.message}`,
        templateRoot,
        files: [],
        conflicts: [],
        createdDirectories: [],
      };
    }
    const result = {
      requested: true,
      status: 'already-installed',
      error: null,
      templateRoot,
      files: preflight.entries.map((entry) => ({
        path: entry.relativePath,
        action: 'already-present',
        bytes: entry.templateContent.length,
        sha256: entry.digest,
      })),
      conflicts: [],
      createdDirectories: [],
      uiDefs: uiDefsReport(),
    };
    const restore = uiDefsRestore();
    if (restore.length > 0) {
      result.restore = restore;
    }
    return result;
  }

  const createdDirectories = [];
  const staged = [];
  const installed = [];

  try {
    for (const entry of toCreate) {
      const parent = path.dirname(entry.destination);
      const missing = [];
      let current = parent;
      while (!fs.existsSync(current)) {
        missing.unshift(current);
        const up = path.dirname(current);
        if (up === current) {
          break;
        }
        current = up;
      }
      createdDirectories.push(...missing);
      fs.mkdirSync(parent, { recursive: true });

      // preflight 後にシンボリックリンクへ差し替えられていないか、書き込み直前に再確認する。
      const linkedParent = findSymlinkComponent(resourcePack, parent);
      if (linkedParent) {
        throw new Error(
          `導入先の親ディレクトリがシンボリックリンクに変わったため中止しました: ${linkedParent}`,
        );
      }

      const tempPath = path.join(
        parent,
        `.invui-${path.basename(entry.destination)}.${process.pid}.${crypto.randomBytes(6).toString('hex')}.tmp`,
      );
      const tempIdentity = writeExclusiveTempFile(tempPath, entry.templateContent);
      staged.push({ ...entry, tempPath, tempIdentity });
    }

    for (const entry of staged) {
      entry.identity = placeFileWithoutOverwrite(entry.tempPath, entry.destination);
      installed.push(entry);
      fs.unlinkSync(entry.tempPath);
      entry.tempPath = null;
    }

    // ファイル配置後の最後に追記する。ここで失敗したら catch が追加済みファイルを戻す。
    registerNow();
  } catch (error) {
    const cleanupErrors = [];
    for (const entry of installed) {
      const cleanup = removeDestinationIfOwned(entry.destination, entry.identity, entry.templateContent);
      if (!cleanup.removed) {
        cleanupErrors.push(`追加済みファイルを戻せません: ${entry.destination} (${cleanup.reason})`);
      }
    }
    for (const entry of staged) {
      if (entry.tempPath) {
        const cleanup = removeDestinationIfOwned(entry.tempPath, entry.tempIdentity);
        if (!cleanup.removed) {
          cleanupErrors.push(`一時ファイルを削除できません: ${entry.tempPath} (${cleanup.reason})`);
        }
      }
    }
    for (const dir of [...createdDirectories].reverse()) {
      try {
        fs.rmdirSync(dir);
      } catch (cleanupError) {
        if (cleanupError.code !== 'ENOENT' && cleanupError.code !== 'ENOTEMPTY') {
          cleanupErrors.push(`作成したディレクトリを戻せません: ${dir} (${cleanupError.message})`);
        }
      }
    }

    return {
      requested: true,
      status: 'failed',
      error:
        `導入中に失敗したためロールバックしました: ${error.message}` +
        (cleanupErrors.length > 0 ? ` / ${cleanupErrors.join(' / ')}` : ''),
      templateRoot: path.join(PACKAGE_ROOT, 'resource_pack'),
      files: [],
      conflicts: [],
      createdDirectories: [],
    };
  }

  return {
    requested: true,
    status: 'installed',
    error: null,
    templateRoot,
    files: [
      ...preflight.entries
        .filter((entry) => entry.action === 'already-present')
        .map((entry) => ({
          path: entry.relativePath,
          action: 'already-present',
          bytes: entry.templateContent.length,
          sha256: entry.digest,
        })),
      ...installed.map((entry) => ({
        path: entry.relativePath,
        action: 'created',
        bytes: entry.templateContent.length,
        sha256: entry.digest,
      })),
    ],
    conflicts: [],
    createdDirectories,
    uiDefs: uiDefsReport(),
    restore: [
      ...installed.map((entry) => `rm "${entry.destination}"`),
      ...(createdDirectories.length > 0
        ? [`rmdir "${path.dirname(installed[0].destination)}"（空の場合のみ）`]
        : []),
      ...uiDefsRestore(),
    ],
  };
}

// 同梱 resource_pack から生成内容を作る。manifest の UUID だけは毎回作り直し、
// 同じテンプレートから作ったパック同士が UUID で衝突しないようにする。
function renderGeneratedPack() {
  const bundledRoot = path.join(PACKAGE_ROOT, 'resource_pack');
  const manifest = JSON.parse(fs.readFileSync(path.join(bundledRoot, 'manifest.json'), 'utf8'));
  if (!manifest || typeof manifest !== 'object' || !manifest.header || typeof manifest.header !== 'object') {
    throw new Error('同梱 manifest.json に header がありません');
  }

  const used = new Set();
  const assignUuid = (target) => {
    let uuid = crypto.randomUUID();
    while (used.has(uuid)) {
      uuid = crypto.randomUUID();
    }
    used.add(uuid);
    target.uuid = uuid;
    return uuid;
  };

  const uuids = [{ path: 'manifest.json#header.uuid', uuid: assignUuid(manifest.header) }];
  const modules = Array.isArray(manifest.modules) ? manifest.modules : [];
  modules.forEach((module, index) => {
    if (module && typeof module === 'object') {
      uuids.push({ path: `manifest.json#modules[${index}].uuid`, uuid: assignUuid(module) });
    }
  });

  const description = typeof manifest.header.description === 'string' ? manifest.header.description.trim() : '';
  manifest.header.description = description ? `${description} ${GENERATED_NOTE}` : GENERATED_NOTE;

  const files = [
    {
      relativePath: 'manifest.json',
      content: Buffer.from(`${JSON.stringify(manifest, null, 2)}\n`),
    },
  ];
  for (const relativePath of GENERATED_FILES) {
    if (relativePath === 'manifest.json') {
      continue;
    }
    files.push({ relativePath, content: fs.readFileSync(path.join(bundledRoot, relativePath)) });
  }

  return { files, uuids };
}

// 出力先の既存パス・シンボリックリンク・ファイルを上書きしないための検査。
function inspectGeneratedOutput(outputRoot) {
  const { root } = path.parse(outputRoot);
  let current = root;

  for (const part of outputRoot.slice(root.length).split(path.sep).filter(Boolean)) {
    current = path.join(current, part);
    let stat;
    try {
      stat = fs.lstatSync(current);
    } catch (error) {
      if (error.code !== 'ENOENT') {
        return {
          status: 'failed',
          error: `出力先を確認できません: ${current} (${error.message})`,
          conflict: null,
        };
      }
      continue;
    }
    if (stat.isSymbolicLink()) {
      return {
        status: 'conflict',
        error: null,
        conflict: {
          path: current,
          reason: '出力先の経路にシンボリックリンクがあります。パック外へ書き込まないため生成しません。',
        },
      };
    }
    if (current === outputRoot) {
      return {
        status: 'conflict',
        error: null,
        conflict: { path: current, reason: '出力先が既に存在します。上書きしません。' },
      };
    }
    if (!stat.isDirectory()) {
      return {
        status: 'conflict',
        error: null,
        conflict: { path: current, reason: '出力先の経路上にファイルがあります。上書きしません。' },
      };
    }
  }

  return { status: 'ok', error: null, conflict: null };
}

// 欠けている親ディレクトリを上から順に作り、作成したものだけを記録する。
function createMissingDirectories(dir, createdDirectories) {
  const missing = [];
  let current = dir;
  while (!fs.existsSync(current)) {
    missing.unshift(current);
    const up = path.dirname(current);
    if (up === current) {
      break;
    }
    current = up;
  }
  for (const target of missing) {
    // recursive は使わない。既に存在すれば EEXIST で失敗し、他人のディレクトリを掴まない。
    fs.mkdirSync(target);
    createdDirectories.push(target);
  }
}

function generateResourcePack(outputRoot) {
  const result = {
    command: GENERATE_COMMAND,
    output: outputRoot,
    status: 'failed',
    error: null,
    files: [],
    conflicts: [],
    createdDirectories: [],
    uuids: [],
    uiConnectRegistered: false,
    warnings: GENERATE_WARNINGS,
  };

  let rendered;
  try {
    rendered = renderGeneratedPack();
  } catch (error) {
    result.error = `同梱テンプレートから生成内容を作れません: ${error.message}`;
    return result;
  }
  result.uuids = rendered.uuids;

  if (path.parse(outputRoot).root === outputRoot) {
    result.status = 'conflict';
    result.conflicts = [{ path: outputRoot, reason: 'ファイルシステムのルートは出力先に指定できません。' }];
    result.error = '既存のパスと競合したため生成しませんでした。既存のファイルとディレクトリは変更していません。';
    return result;
  }

  const inspection = inspectGeneratedOutput(outputRoot);
  if (inspection.status !== 'ok') {
    result.status = inspection.status;
    result.conflicts = inspection.conflict ? [inspection.conflict] : [];
    result.error =
      inspection.status === 'conflict'
        ? '既存のパスと競合したため生成しませんでした。既存のファイルとディレクトリは変更していません。'
        : inspection.error;
    return result;
  }

  const createdDirectories = [];
  const createdFiles = [];
  const stagedTemps = [];

  try {
    for (const file of rendered.files) {
      const destination = path.join(outputRoot, file.relativePath);
      createMissingDirectories(path.dirname(destination), createdDirectories);
      const tempPath = `${destination}.${process.pid}.${crypto.randomBytes(6).toString('hex')}.tmp`;
      const tempIdentity = writeExclusiveTempFile(tempPath, file.content);
      stagedTemps.push({ path: tempPath, identity: tempIdentity });
      const identity = placeFileWithoutOverwrite(tempPath, destination);
      // 配置に成功した時点で記録する。直後の temp 削除が失敗しても、
      // ロールバックがこのファイルを「作成していない」と誤認して残さないため。
      createdFiles.push({ destination, identity, relativePath: file.relativePath, content: file.content });
      fs.unlinkSync(tempPath);
      stagedTemps.pop();
    }
  } catch (error) {
    const cleanupErrors = [];
    for (const file of createdFiles) {
      const cleanup = removeDestinationIfOwned(file.destination, file.identity, file.content);
      if (!cleanup.removed) {
        cleanupErrors.push(`作成済みファイルを削除できません: ${file.destination} (${cleanup.reason})`);
      }
    }
    for (const staged of stagedTemps) {
      const cleanup = removeDestinationIfOwned(staged.path, staged.identity);
      if (!cleanup.removed) {
        cleanupErrors.push(`一時ファイルを削除できません: ${staged.path} (${cleanup.reason})`);
      }
    }
    for (const dir of [...createdDirectories].reverse()) {
      try {
        fs.rmdirSync(dir);
      } catch (cleanupError) {
        if (cleanupError.code !== 'ENOENT' && cleanupError.code !== 'ENOTEMPTY') {
          cleanupErrors.push(`作成したディレクトリを削除できません: ${dir} (${cleanupError.message})`);
        }
      }
    }

    result.error =
      `生成中に失敗したため、この CLI が作成したものだけを削除しました: ${error.message}` +
      (cleanupErrors.length > 0 ? ` / ${cleanupErrors.join(' / ')}` : '');
    return result;
  }

  result.status = 'generated';
  result.uiConnectRegistered = true;
  result.files = createdFiles.map((file) => ({
    path: file.relativePath,
    action: 'created',
    bytes: file.content.length,
    sha256: sha256(file.content),
  }));
  result.createdDirectories = createdDirectories;
  return result;
}

